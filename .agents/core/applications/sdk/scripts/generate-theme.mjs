import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {themeColors, themeColorNames, themeColorProperties, themeColorDefinitions} from '../src/theme.ts';

const declarations = theme => '  color-scheme: ' + theme + ';\n' + themeColorNames.map(name =>
  `  ${themeColorProperties[name]}: ${themeColors[theme][name]};`,
).join('\n');

export function generateThemeCSS() {
  return `/* Generated by scripts/generate-theme.mjs from src/theme.ts. Do not edit values here. */
.ksf-theme, [data-ksf-theme] {
${declarations('light')}
}
[data-ksf-theme="dark"] {
${declarations('dark')}
}
@media (prefers-color-scheme: dark) {
  .ksf-theme:not([data-ksf-theme]), [data-ksf-theme="system"] {
${declarations('dark').split('\n').map(line => '  ' + line).join('\n')}
  }
}
`;
}

export function generateThemeDocumentation() {
  return '# 浅深主题公共配色\n\n由 `src/theme.ts` 生成，修改配色后执行 `npm run theme:generate`；`npm run theme:check` 核对一致性。仅两套颜色主题，system 表示跟随系统，并非第三套配色。\n\n'
    + 'SDK 新组件与应用共用 `--ksf-color-*`；React 内联样式可用 `themeVars`，需要原始值时读取 `themeColors.light`／`dark`。完整接入说明见 [SDK README](README.md#公共主题颜色)。\n\n'
    + '| 用途 | CSS 变量 | 浅色 | 深色 | 使用说明 |\n| --- | --- | --- | --- | --- |\n'
    + themeColorNames.map(name => `| ${themeColorDefinitions[name].label} | \`${themeColorProperties[name]}\` | \`${themeColors.light[name]}\` | \`${themeColors.dark[name]}\` | ${themeColorDefinitions[name].usage} |`).join('\n') + '\n\n'
    + '正文、辅助文字与主操作文字在背景／分区／浮层上按 4.5:1 核对；主色上文字、选区与语义色使用表中规定的搭配。交互边界与焦点轮廓按 3:1 核对；轻边界只用于装饰分隔。透明遮罩不作为正文底色。组件最终的可读性仍取决于实际字号、背景、层级和使用方式。\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outputs = [[new URL('../src/theme.css', import.meta.url), generateThemeCSS()],
    [new URL('../THEME-COLORS.md', import.meta.url), generateThemeDocumentation()]];
  for (const [target, content] of outputs) {
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8') !== content) throw Error(fileURLToPath(target) + ' 与配色源不一致，请执行 npm run theme:generate。');
    } else { await writeFile(target, content); console.log('Generated ' + fileURLToPath(target)); }
  }
  if (process.argv.includes('--check')) console.log('Theme CSS and documentation match the public palettes.');
}
